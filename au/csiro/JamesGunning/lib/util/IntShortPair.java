package au.csiro.JamesGunning.lib.util;
/**
   Useful Class for pairs of ints,shorts
   in form A,B

   @author james.gunning@dpr.csiro.au
   @version 1.0, Aug 2010
*/
public class IntShortPair
{
  public int A;
  public short B;
  
  public IntShortPair(int A, short B)
  {
	this.A = A; 
	this.B = B;
  }
}

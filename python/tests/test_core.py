def test_fluid_probability_ignores_pinched_out_layers(tmp_path):
    # sand usually pinched out and no seismic: the raw label stays at the 50/50
    # prior, but gas *present* is only as likely as the sand itself
    cfg = load_config(write_case(tmp_path, three_layer()))
    cfg.layers[1].time = 1.955
    r = invert_trace(cfg, None, 2000, np.random.default_rng(0), ignore_seismic=True)
    absent, brine, oil, lsg, gas = r.fluid_probabilities()[1]
    assert absent + brine + oil + lsg + gas == pytest.approx(1.0)
    assert absent == pytest.approx(r.pinchout_probability()[1])
    assert r.fluid_probabilities(present_only=False)[1][3] == pytest.approx(0.5, abs=0.06)
    assert gas == pytest.approx(0.5 * (1 - absent), abs=0.06)


def test_parallel_runs_match_serial_and_time_traces():
    inv = Inversion.from_files(NG_WEDGE / "ModelDescription.xml", NG_WEDGE / "prior_traces.su")
    kw = dict(traces=[0, 7, 14], seed=3, burn_in=100, thin=5, n_chains=16)
    serial = inv.run(40, **kw)
    parallel = inv.run(40, n_jobs=2, **kw)
    for a, b in zip(serial, parallel):
        np.testing.assert_allclose(a.samples["t"], b.samples["t"])
    # posterior impedance / synthetic traces on the data grid
    s = inv.stacks[0]
    times = s.t0[0] + s.dt * np.arange(s.n_samples)
    tt = serial[1].time_traces(times, keep=2)
    assert tt["Zp_mean"].shape == times.shape and tt["Zp_samples"].shape == (2, len(times))
    # the mean synthetic fits the (noise-free) data to within the declared noise
    window = (times > 1.85) & (times < 2.05)
    resid = s.data[7][window] - tt["synthetic_mean"][window]
    assert np.sqrt(np.mean(resid**2)) < inv.cfg.stacks[0].noise_rms
    # impedance above the model is the top layer's, below it the bottom layer's
    r = serial[1]
    assert tt["Zp_mean"][0] == pytest.approx(r.mean("Z_eff")[0], rel=1e-6)
    assert tt["Zp_mean"][-1] == pytest.approx(r.mean("Z_eff")[2], rel=1e-6)


def test_time_scan_never_worse_than_picks(tmp_path):
    # truth: gas sand 20 ms thick; the base pick is 15 ms too deep
    from pydelivery.modes import _fit, starting_points

    truth = lambda m: _with_times(m, 1.900, 1.920)  # noqa: E731
    xml = write_case(tmp_path, three_layer().replace("<time>1960</time>", "<time>1935</time>"),
                     "bgb", truth_m=truth)
    inv = Inversion.from_files(xml)
    cfg, seis = inv.trace_setup(0)
    model = StateModel(cfg, next(s for s in enumerate_fluid_states(cfg) if s.label == "bgb"), seis)
    best = {}
    for scan in (False, True):
        fits = [_fit(model, s, False) for s in starting_points(model, np.random.default_rng(0), 0, scan)]
        best[scan] = min((f for f in fits if f is not None), key=lambda f: f[1])
    assert best[True][1] <= best[False][1] + 1e-9
    assert model.evaluate(best[True][0][None]).seismic_nll[0] < 0.5


def _with_times(model, top, base):
    m = model.prior_mean.copy()
    m[model.index[("t", 1)]], m[model.index[("t", 2)]] = top, base
    return m


def test_kmeans_facies_names_clusters_by_nearest_facies():
    from pydelivery.qc import classify_facies, kmeans

    rng = np.random.default_rng(0)
    X = np.concatenate([rng.normal(0, 0.1, (200, 2)), rng.normal(3, 0.1, (100, 2))])
    lab, C = kmeans(X, 2)
    assert sorted(np.bincount(lab)) == [100, 200]
    facies = [{"name": "shale", "Zp": 6.6e6, "Zs": 2.6e6}, {"name": "gas sand", "Zp": 5.3e6, "Zs": 3.0e6}]
    Zp = np.concatenate([rng.normal(6.6e6, 2e4, 300), rng.normal(5.3e6, 2e4, 50)])
    Zs = np.concatenate([rng.normal(2.6e6, 1e4, 300), rng.normal(3.0e6, 1e4, 50)])
    names, C, nearest = classify_facies(Zp, Zs, facies)
    assert (names[:300] == 0).all() and (names[300:] == 1).all()
    # three clusters on two facies: two clusters share a name rather than mislabel
    names3, _, nearest3 = classify_facies(Zp, Zs, facies + [{"name": "brine sand", "Zp": 6.5e6, "Zs": 3.2e6}])
    assert (names3[300:] == 1).all() and (names3[:300] == 0).all()


def test_facies_present_needs_majority_probability():
    from pydelivery.qc import facies_present

    class R:  # minimal stand-in for TraceResult
        def __init__(self, p):
            self.p = p

        def fluid_probabilities(self):
            return np.array([[1, 0, 0, 0, 0], self.p])

    facies = [{"name": "shale", "permeable": False},
              {"name": "sand + brine", "permeable": True, "fluid": "brine"},
              {"name": "sand + gas", "permeable": True, "fluid": "gas"}]
    # gas sand > 0.5 at 60 of 100 traces; brine sand most likely (0.45) at 30 traces but never > 0.5,
    # and > 0.5 at only 2 traces
    res = [R([0, 0.1, 0, 0, 0.9])] * 60 + [R([0.35, 0.45, 0, 0, 0.2])] * 30 + \
          [R([0.4, 0.6, 0, 0, 0])] * 2 + [R([1, 0, 0, 0, 0])] * 8
    assert [f["name"] for f in facies_present(res, facies, layer=1)] == ["shale", "sand + gas"]
